# Compiles `.cursorrules` and `CLAUDE.md` from MigrationDelta
from pathlib import Path
from typing import Optional
from backend.schemas.migration_models import (
    MigrationDelta,
    Stage4VerificationReport,
    Stage5ExportBundle,
)


def generate_context_infrastructure_files(
    patched_repo_dir: Path,
    migration_delta: MigrationDelta,
    stage4_report: Stage4VerificationReport,
    pr_url: Optional[str] = None,
) -> Stage5ExportBundle:
    """
    Generates `.cursorrules` and `CLAUDE.md` inside `patched_repo_dir` containing
    strict anti-regression rules discovered during the migration and sandbox verification
    for ANY target library.
    """
    rules_bullets = []
    for r in migration_delta.rules:
        rules_bullets.append(
            f"### {r.symbol}\n"
            f"- **FORBIDDEN (Legacy {migration_delta.from_version}):** `{r.old_syntax}`\n"
            f"- **REQUIRED (Target {migration_delta.to_version}):** `{r.new_syntax}`\n"
            f"- **Required Imports:** `{', '.join(r.required_imports)}`\n"
            f"- **Silent Semantic Drift Warning:** {r.breaking_gotcha}\n"
            f"- **Verified Source:** {r.source_url}\n"
        )

    rules_body = "\n".join(rules_bullets)

    # Dynamic lessons learned from Stage 4 sandbox self-healing
    self_heal_lessons = []
    if stage4_report.self_healing_triggered:
        for att in stage4_report.attempts:
            if att.healed_file:
                self_heal_lessons.append(
                    f"- Autonomous self-healing patched `{att.healed_file}` to eliminate silent semantic drift. "
                    f"Always verify default arguments, validation lifecycles, and keyword arguments in {migration_delta.library} {migration_delta.to_version}."
                )
    if not self_heal_lessons:
        self_heal_lessons.append(
            f"- All {len(stage4_report.attempts)} sandbox verification tests passed. Follow modern {migration_delta.library} {migration_delta.to_version} API contracts strictly."
        )

    lessons_body = "\n".join(self_heal_lessons)

    cursorrules_content = f"""# ⚡ AUTO-GENERATED BY DRIFTZERO (Nebius Token Factory + Tavily Grounded)
# Library Upgrade Enforced: {migration_delta.library} {migration_delta.from_version} -> {migration_delta.to_version}
# Verification Status: {stage4_report.final_status} ({stage4_report.total_attempts} Sandbox Runs)

You are editing a repository migrated to `{migration_delta.library}=={migration_delta.to_version}`.
NEVER generate legacy `{migration_delta.from_version}` syntax from your pre-training weights.

## Mandatory Syntax & Semantic Rules
{rules_body}

## Self-Healing Sandbox Lessons Learned
{lessons_body}
"""

    claude_md_content = f"""# CLAUDE.md — Repository Context & Migration Guardrails

## Active Dependency Standards
- **{migration_delta.library}**: `{migration_delta.to_version}` (Upgraded from `{migration_delta.from_version}` via DriftZero)
- **Verification Suite**: `pytest test_migration_parity.py -v`

## Strict Coding Rules for AI Agents
{rules_body}

## Sandbox Quality Assurance
{lessons_body}
"""

    cursor_path = patched_repo_dir / ".cursorrules"
    claude_path = patched_repo_dir / "CLAUDE.md"

    cursor_path.write_text(cursorrules_content, encoding="utf-8")
    claude_path.write_text(claude_md_content, encoding="utf-8")

    branch_name = f"driftzero/migrate-{migration_delta.library.lower()}-{migration_delta.to_version}"
    title = f"chore(deps): autonomous migration of {migration_delta.library} to {migration_delta.to_version}"

    return Stage5ExportBundle(
        cursorrules_path=str(cursor_path),
        claude_md_path=str(claude_path),
        cursorrules_content=cursorrules_content,
        claude_md_content=claude_md_content,
        pr_branch_name=branch_name,
        pr_title=title,
        pr_url=pr_url or f"https://github.com/driftzero/{migration_delta.library}-migration/pull/1",
        status="READY_FOR_PR",
    )